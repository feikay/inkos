import type { ShortStoryChapterPlan, ShortStoryTheme } from "../../schema.js";
import type { ShortStoryCast, ShortStorySceneDraft } from "../index.js";

export function resolveBetrayalRevengeCast(_theme: ShortStoryTheme): ShortStoryCast {
  return {
    hero: "林晚",
    villain: "顾沉",
    rival: "苏蔓",
    child: "顾念",
  };
}

export function createBetrayalRevengeScene(
  chapter: ShortStoryChapterPlan,
  cast: ShortStoryCast,
): ShortStorySceneDraft {
  const base = createBaseScene(chapter, cast);
  return {
    ...base,
    finalBridge: `${cast.hero}终于不用再向任何人证明自己受过的伤。她把旧账封存，也把余生重新拿回手里。`,
  };
}

